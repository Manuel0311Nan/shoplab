/** Un emoji, aunque lleve modificadores (tono, ZWJ): como mucho unas pocas unidades. */
const MAX_LONGITUD_EMOJI = 16;

/** Exactamente un emoji (un solo grafema con pictograma), sin texto alrededor. */
export function esEmoji(texto: string): boolean {
  const limpio = texto.trim();
  if (limpio === "" || limpio.length > MAX_LONGITUD_EMOJI) return false;
  const grafemas = [...new Intl.Segmenter("es", { granularity: "grapheme" }).segment(limpio)];
  return grafemas.length === 1 && /\p{Extended_Pictographic}/u.test(limpio);
}

