export function emojiPorDefecto(nombre: string): string | null {
  const texto = ` ${normalizarNombre(nombre)} `;
  for (const [clave, emoji] of POR_NOMBRE) {
    if ([clave, `${clave}s`, `${clave}es`].some((forma) => texto.includes(` ${forma} `))) {
      return emoji;
    }
  }
  return null;
}
