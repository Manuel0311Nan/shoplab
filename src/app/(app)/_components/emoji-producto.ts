import type { EmojisProductos } from "@/contracts/memoria";
import { emojiPorDefecto } from "@/shared/kernel/emoji";
import { normalizarNombre } from "@/shared/kernel/texto";

/** El emoji con que se ve un producto: el elegido por el hogar o el de por defecto. */
export function emojiDe(emojis: EmojisProductos, nombre: string): string | null {
  return emojis[normalizarNombre(nombre)] ?? emojiPorDefecto(nombre);
}

